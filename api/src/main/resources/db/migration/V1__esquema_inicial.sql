-- V1: o esquema inicial do TaskForge.
-- Ate aqui o Hibernate criava as tabelas sozinho (ddl-auto=update).
-- A partir de agora, QUALQUER mudanca no banco e um novo arquivo V<n>__.
-- Num banco que ja existe (o do deploy), o baseline-on-migrate marca o que
-- ja esta como "versao 1" e o Flyway NAO roda este V1.

CREATE TABLE usuario (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(255),
    email  VARCHAR(255),
    senha  VARCHAR(255)
);

CREATE TABLE tarefa (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(255),
    prioridade  INTEGER,
    concluida   BOOLEAN
);

CREATE TABLE comentario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao  VARCHAR(255),
    autor      VARCHAR(255)
);
